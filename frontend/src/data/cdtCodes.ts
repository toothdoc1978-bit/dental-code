/** Map of code -> CDTCode for O(1) lookups */
export const CDT_CODE_MAP: Record<string, CDTCode> = Object.fromEntries(
  CDT_CODES.map((c) => [c.code, c]),
);

/** Return all codes in a given category */
export function getCDTCodesByCategory(category: string): CDTCode[] {
  return CDT_CODES.filter((c) => c.category === category);
}

/** Return all audit-sensitive codes */
export function getAuditSensitiveCodes(): CDTCode[] {
  return CDT_CODES.filter((c) => c.auditSensitive);
}

